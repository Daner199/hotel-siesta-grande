--
-- 1. Método TRANSFERENCIA (decisión de Daner, además de efectivo, QR y tarjeta).
-- 2. Cuenta bancaria del hotel para transferencias (datos de EJEMPLO, se editan en "Datos del hotel").
-- 3. cobro_qr: cada QR generado (monto fijo, vence a los 15 min, lo paga Banco Siesta por webhook).
-- 4. transferencia: datos que solo tienen los pagos por transferencia (comprobante y revisión).
-- 5. recibo: uno por pago aprobado, numerado sin saltos (REC-000001). saldo_pendiente es una foto
--    del momento (igual que precio_noche_aplicado). Los recibos de pagos que ya existían los crea
--    "php artisan recibos:generar".
--
-- Deshacer:
--   DROP TABLE recibo, transferencia, cobro_qr;
--   ALTER TABLE hotel DROP COLUMN cuenta_banco, DROP COLUMN cuenta_tipo, DROP COLUMN cuenta_numero, DROP COLUMN cuenta_titular;
--   DELETE FROM metodo_pago WHERE nombre = 'TRANSFERENCIA';


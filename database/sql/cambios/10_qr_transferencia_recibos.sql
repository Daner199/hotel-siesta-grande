-- 3. Cobros con QR dinámico
CREATE TABLE cobro_qr (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token                 varchar(64)   NOT NULL,
    reserva_id            bigint        NOT NULL,
    monto                 numeric(12,2) NOT NULL,
    vence_en              timestamp     NOT NULL,
    estado                varchar(15)   NOT NULL DEFAULT 'PENDIENTE',
    pago_id               bigint,
    creado_por_usuario_id bigint        NOT NULL,
    created_at            timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_cobro_qr_token UNIQUE (token),
    CONSTRAINT uq_cobro_qr_pago  UNIQUE (pago_id),
    CONSTRAINT chk_cobro_qr_monto CHECK (monto > 0),
    CONSTRAINT chk_cobro_qr_estado CHECK (estado IN ('PENDIENTE', 'PAGADO', 'RECHAZADO', 'VENCIDO', 'ANULADO')),
    CONSTRAINT chk_cobro_qr_pagado CHECK (estado <> 'PAGADO' OR pago_id IS NOT NULL),
    CONSTRAINT fk_cobro_qr_reserva FOREIGN KEY (reserva_id)
        REFERENCES reserva (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_cobro_qr_pago FOREIGN KEY (pago_id)
        REFERENCES pago (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_cobro_qr_usuario FOREIGN KEY (creado_por_usuario_id)
        REFERENCES usuario (id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX idx_cobro_qr_reserva ON cobro_qr (reserva_id, estado);

-- 4. Transferencias (el pago queda PENDIENTE = "en revisión" hasta que recepción lo revisa)
CREATE TABLE transferencia (
    pago_id                 bigint       PRIMARY KEY,
    numero_operacion        varchar(30)  NOT NULL,
    comprobante             varchar(255) NOT NULL,
    revisado_por_usuario_id bigint,
    fecha_revision          timestamp,
    motivo_rechazo          varchar(255),

    CONSTRAINT uq_transferencia_operacion UNIQUE (numero_operacion),
    CONSTRAINT chk_transferencia_revision CHECK ((revisado_por_usuario_id IS NULL) = (fecha_revision IS NULL)),
    CONSTRAINT fk_transferencia_pago FOREIGN KEY (pago_id)
        REFERENCES pago (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_transferencia_revisor FOREIGN KEY (revisado_por_usuario_id)
        REFERENCES usuario (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 5. Recibos (no son facturas)
CREATE TABLE recibo (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero             integer       NOT NULL,
    pago_id            bigint        NOT NULL,
    fecha_emision      timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    saldo_pendiente    numeric(12,2) NOT NULL,
    token_verificacion varchar(64)   NOT NULL,

    CONSTRAINT uq_recibo_numero UNIQUE (numero),
    CONSTRAINT uq_recibo_pago   UNIQUE (pago_id),
    CONSTRAINT uq_recibo_token  UNIQUE (token_verificacion),
    CONSTRAINT chk_recibo_numero CHECK (numero > 0),
    CONSTRAINT chk_recibo_saldo  CHECK (saldo_pendiente >= 0),
    CONSTRAINT fk_recibo_pago FOREIGN KEY (pago_id)
        REFERENCES pago (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

COMMIT;
